// tileset, the .ablk, registration and the map's script file. Every step is idempotent: rerunning
// the port changes nothing that's already right. The port works everything out first, then writes
// only if no file it writes was changed by another program since it read it. Each project format
// it writes is written per the project's variant of that feature (shared/features.ts).

