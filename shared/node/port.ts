export interface PortContext {
	entry: MapEntry;
	tilesetEntry: TilesetEntry;
	gen1Map: GameMap;
	gen1Coll: Gen1Collision;
	cseTileset: Tileset;
	/** The mapping after fingerprint checks (moved content re-pointed). */
	mapping: Mapping;
	/** False when this tileset pair has no saved mapping yet (the page pre-fills it, D36). */
	mappingSaved: boolean;
	/** What the fingerprint check found against the current tileset. */
	reconciled: Pick<Reconcile, "moved" | "changed">;
	/** Gen 1 blocks the map uses, plus its border block. */
	used: number[];
	result: MappingResult;
	/** The project's collision names, which built blocks and warp squares are written in. */
	collisionNames: Supported<"collisionNames">;
}

export function portContext(config: Config, gen1Const: string, mappingOverride?: Mapping): PortContext {
	const cseFiles = gameFiles(config, "cse");
	const cseRoot = cseFiles.root;
	const entry = mapEntry(cseRoot, gen1Const);
	const gen1Files = gameFiles(config, entry.game);
	const gen1Map = loadGen1Map(gen1Files, entry.game, gen1Const);
	const tsEntry = tilesetEntry(cseRoot, gen1Map.tileset.constName);
	const gen1Coll = loadGen1Collision(gen1Files, gen1Map.tileset.constName);
	const cseTilesetConst = entry.tileset ?? tsEntry.cse; // a map may pick its own
	const cseTileset = loadCseTileset(cseFiles, cseTilesetConst, formatsOf(cseFiles, TILESET_FEATURES));
	const mappingSaved = existsSync(mappingFile(cseRoot, gen1Map.tileset.constName, cseTilesetConst));
	const rec = reconcile(mappingOverride ?? loadMapping(cseRoot, gen1Map.tileset.constName, cseTilesetConst), cseTileset);
	const mapping = rec.mapping;
	const used = [...new Set([...gen1Map.blocks, ...(gen1Map.borderBlock !== undefined ? [gen1Map.borderBlock] : [])])].sort((a, b) => a - b);
	const { collisionNames } = formatsOf(cseFiles, ["collisionNames"]);
	const result = resolveMapping(mapping, gen1Map.tileset, gen1Coll, cseTileset, used, { warp: tsEntry.warpColl, names: collisionNames });
	return { entry, tilesetEntry: tsEntry, gen1Map, gen1Coll, cseTileset, mapping, mappingSaved, reconciled: { moved: rec.moved, changed: rec.changed }, used, result, collisionNames };
}

/** A map's events, made from Gen 1's (none for a replaced map, which keeps its own script). */
export function portEvents(config: Config, gen1Const: string, entry: MapEntry, gen1Name: string): MapEvents {
	if (entry.target === "replace") return { objectConsts: [], bgEvents: [], objectEvents: [], notes: [], scripts: [], flags: [], trainers: [], missing: [], report: [], marks: [], extraWarps: [], callbacks: [], initFlags: [], collisionSquares: [] };
	const cseFiles = gameFiles(config, "cse");
	const cseMaps = mapConsts(cseFiles.text("constants/map_constants.asm"));
	const table = mapTable(cseFiles.root);
	// A Gen 1 map's CSE constant when it's set up and in the project (this map counts: it's being ported).
	const ported = (g: string) => {
		const e = table[g];
		return e && (e.const === entry.const || cseMaps.has(e.const)) ? e.const : undefined;
	};
	const tables = eventTables(cseFiles.root, projectFeatures(cseFiles).defaults);
	const formats = formatsOf(cseFiles, EVENT_FEATURES);
	return gen1MapEvents(gameFiles(config, entry.game), gen1Name, gen1Const, entry, cseNames(cseFiles, formats.itemEvents), tables, formats, ported);
}

/** The features the events of a map are written in. */
