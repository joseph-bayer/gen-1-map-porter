const PORTED_FLAGS = "; Ported Gen 1 maps (gen1-map-porter)";

/**
 * Room for new event flags. The array is a fixed size (`const_next 2048` pads it up to NUM_EVENTS),
 * and there may be no room to grow it, so new flags take the free places below the padding, then
 * the `const_skip ; unused` slots.
 */
function flagRoom(lines: string[]): { padAt: number; free: number; skips: number[]; have: Set<string> } {
	const have = new Set(lines.flatMap((l) => l.match(/^\s*const\s+(EVENT_\w+)/)?.[1] ?? []));
	const numAt = lines.findIndex((l) => /^(?:DEF\s+)?NUM_EVENTS\b/.test(l));
	let padAt = numAt - 1;
	while (padAt > 0 && !lines[padAt]!.trim()) padAt--;
	const pad = lines[padAt]?.match(/^\s*const_next\s+(\$?[0-9a-fA-F]+)/);
	if (numAt < 0 || !pad) return { padAt: numAt, free: 0, skips: [], have };
	let value = 0;
	const skips: number[] = [];
	for (let i = 0; i < padAt; i++) {
		const l = stripComment(lines[i]!);
		let m: RegExpMatchArray | null;
		if ((m = l.match(/^const_def(?:\s+(\S+))?/))) value = m[1] ? (parseNumber(m[1]) ?? 0) : 0;
		else if ((m = l.match(/^const_skip(?:\s+(\S+))?/))) {
			value += m[1] ? (parseNumber(m[1]) ?? 1) : 1;
			if (!m[1] && /;\s*unused/.test(lines[i]!)) skips.push(i);
		} else if ((m = l.match(/^const_next\s+(\S+)/))) value = parseNumber(m[1]!) ?? value;
		else if (/^const\s+\w/.test(l)) value++;
	}
	return { padAt, free: (parseNumber(pad[1]!) ?? 0) - value, skips, have };
}

/** How many of these flags are new, and how many places there are for new ones. */
export function flagNeeds(flagsText: string, flags: string[]): { needed: number; room: number } {
	const room = flagRoom(flagsText.split(/\r?\n/));
	return { needed: flags.filter((fl) => !room.have.has(fl)).length, room: room.free + room.skips.length };
}

/** New event flags, per way the project sizes its flag list. */
const EVENT_FLAGS: Record<Supported<"eventFlags">, (f: TextFile, flags: string[], errors: string[]) => void> = {
	padded: addEventFlags,
};

/** New event flags: a "Ported Gen 1 maps" block above the padding, then unused slots, in that order. */
function addEventFlags(f: TextFile, flags: string[], errors: string[]): void {
	const lines = linesOf(f);
	const room = flagRoom(lines);
	const add = flags.filter((fl) => !room.have.has(fl));
	if (!add.length) return;
	if (add.length > room.free + room.skips.length) {
		errors.push(`event flags: ${add.length} needed, ${room.free + room.skips.length} left`);
		return;
	}
	const inBlock = add.slice(0, room.free), inSkips = add.slice(room.free);
	// Unused slots first (they're above the block, so filling them doesn't move its line numbers).
	inSkips.forEach((fl, i) => (lines[room.skips[i]!] = `\tconst ${fl} ; was unused (gen1-map-porter)`));
	if (!inBlock.length) return setLines(f, lines);
	let at = lines.findIndex((l) => l.includes(PORTED_FLAGS));
	if (at >= 0) {
		at++;
		while (at < lines.length && /^\s*const\s+EVENT_/.test(lines[at]!)) at++;
	} else {
		lines.splice(room.padAt, 0, PORTED_FLAGS, "");
		at = room.padAt + 1;
	}
	lines.splice(at, 0, ...inBlock.map((fl) => `\tconst ${fl}`));
	setLines(f, lines);
}

const PORTED_INIT = "; Ported Gen 1 maps (gen1-map-porter): boulders that start below a hole";

/** Where flags set at game start go, per way the project sets them. */
const STARTING_FLAGS: Record<Supported<"startingFlags">, { file: string; add(f: TextFile, flags: string[], errors: string[]): void }> = {
	"initialize-events-script": { file: "engine/events/std_scripts.asm", add: addInitializeEventsFlags },
	"initial-events-list": { file: "data/events/initialize_events.asm", add: addInitialEventsFlags },
};

/** Flags set at game start: a block of `dw` lines at the end of the InitialEvents: list, before its `dw -1`. */
function addInitialEventsFlags(f: TextFile, flags: string[], errors: string[]): void {
	if (!flags.length) return;
	const lines = linesOf(f);
	const list = lines.findIndex((l) => /^InitialEvents:/.test(l));
	const end = list < 0 ? -1 : lines.findIndex((l, i) => i > list && /^\s*dw\s+-1\b/.test(l));
	if (end < 0) {
		errors.push("data/events/initialize_events.asm has no InitialEvents: list ending in `dw -1` to put starting flags in");
		return;
	}
	const inList = lines.slice(list, end);
	const add = flags.filter((fl) => !inList.some((l) => new RegExp(`^\\s*dw\\s+${fl}\\b`).test(l)));
	if (!add.length) return;
	const at = inList.findIndex((l) => l.includes(PORTED_INIT));
	if (at >= 0) {
		let i = list + at + 1;
		while (i < end && /^\s*dw\s+EVENT_/.test(lines[i]!)) i++;
		lines.splice(i, 0, ...add.map((fl) => `\tdw ${fl}`));
	} else {
		lines.splice(end, 0, PORTED_INIT, ...add.map((fl) => `\tdw ${fl}`));
	}
	setLines(f, lines);
}

/** Flags set at game start: a block in InitializeEventsScript, just before it marks events initialized. */
function addInitializeEventsFlags(f: TextFile, flags: string[], errors: string[]): void {
	if (!flags.length) return;
	const lines = linesOf(f);
	const add = flags.filter((fl) => !lines.some((l) => new RegExp(`^\\s*setevent\\s+${fl}\\b`).test(l)));
	if (!add.length) return;
	let at = lines.findIndex((l) => l.includes(PORTED_INIT));
	if (at >= 0) {
		at++;
		while (at < lines.length && /^\s*setevent\s/.test(lines[at]!)) at++;
		lines.splice(at, 0, ...add.map((fl) => `\tsetevent ${fl}`));
	} else {
		const end = lines.findIndex((l) => /^\s*setevent\s+EVENT_INITIALIZED_EVENTS\b/.test(l));
		if (end < 0) {
			errors.push("engine/events/std_scripts.asm has no `setevent EVENT_INITIALIZED_EVENTS` to put starting flags before");
			return;
		}
		lines.splice(end, 0, PORTED_INIT, ...add.map((fl) => `\tsetevent ${fl}`));
	}
	setLines(f, lines);
}

/**
 * A new trainer's constant, at the end of its class's trainerclass block. Returns false if it was there.
 * `partyNumber`: where a party's constant must equal its number (def_trainer checks it), the number
 * the new party gets; parties numbered without constants (a leader's rematches) are skipped over.
 */
function addTrainerConst(f: TextFile, t: TrainerAdd, errors: string[], partyNumber?: number): boolean {
	const lines = linesOf(f);
	if (lines.some((l) => new RegExp(`^\\s*const\\s+${t.constName}\\b`).test(l))) return false;
	const start = lines.findIndex((l) => new RegExp(`^\\s*trainerclass\\s+${t.cseClass}\\b`).test(l));
	if (start < 0) {
		errors.push(`constants/trainer_constants.asm has no trainerclass ${t.cseClass}`);
		return false;
	}
	let end = start + 1;
	if (partyNumber === undefined) {
		while (end < lines.length && /^\s*const\s/.test(lines[end]!)) end++;
		lines.splice(end, 0, `\tconst ${t.constName}`);
		setLines(f, lines);
		return true;
	}
	// The class's constants count from 1 (trainerclass starts them there).
	let next = 1;
	for (; end < lines.length; end++) {
		const l = stripComment(lines[end]!);
		const skip = l.match(/^const_skip(?:\s+(\S+))?$/);
		if (skip) next += skip[1] ? (parseNumber(skip[1]) ?? 1) : 1;
		else if (/^const\s/.test(l)) next++;
		else break;
	}
	if (next > partyNumber) {
		errors.push(`trainer class ${t.cseClass} has more constants (${next - 1}) than parties (${partyNumber - 1}), so the new party's constant can't match its number`);
		return false;
	}
	lines.splice(end, 0, ...(next < partyNumber ? [`\tconst_skip ${partyNumber - next} ; parties numbered without constants`] : []), `\tconst ${t.constName}`);
	setLines(f, lines);
	return true;
}

/** How many parties a class's group in data/trainers/parties.asm has (def_trainer lines, up to the next SECTION). */
function defTrainerCount(f: TextFile, group: string | undefined): number | undefined {
	const lines = linesOf(f);
	const start = group ? lines.findIndex((l) => l.startsWith(`${group}:`)) : -1;
	if (start < 0) return undefined;
	let n = 0;
	for (let i = start + 1; i < lines.length && !/^\s*SECTION\b/.test(lines[i]!); i++) if (/^\s*def_trainer\b/.test(lines[i]!)) n++;
	return n;
}

/** How a species or move is stored, per index width (a species with its form is `dp`). */
const INDEX_DATA: Record<Supported<"indexWidth">, string> = { "16-bit": "dw", "8-bit": "db", "9-bit-forms": "dp" };

const trainerType = (t: TrainerAdd) => (t.moves ? "TRAINERTYPE_MOVES" : "TRAINERTYPE_NORMAL");

/** A comment naming a Pokémon's Gen 1 moves the project doesn't have, for the line its moves are on. */
const droppedNote = (m: TrainerAdd["mons"][number]) => (m.dropped?.length ? ` ; dropped Gen 1's ${m.dropped.join(", ")} (not in the project)` : "");

/** A new party at the end of its class's group in data/trainers/parties.asm (order = constants'), per party format. */
const ADD_PARTY: Record<Supported<"trainerParties">, (lines: string[], start: number, t: TrainerAdd, width: Supported<"indexWidth">, errors: string[]) => void> = {
	// next_list_item before each party; the group ends at end_list_items.
	"list-items": (lines, start, t, width) => {
		let end = start + 1, count = 0;
		for (; end < lines.length && !/^\s*end_list_items\b/.test(lines[end]!); end++) if (/^\s*next_list_item\b/.test(lines[end]!)) count++;
		lines.splice(end, 0,
			`\tnext_list_item ; ${t.cseClass} (${count + 1})`,
			`\tdb "${t.name}@", ${trainerType(t)} ; ported from Gen 1's ${t.source}`,
			...t.mons.flatMap((m) => [`\tdb ${m.level}`, `\t${INDEX_DATA[width]} ${m.species}`, ...(m.moves ? [`\t${INDEX_DATA[width]} ${m.moves.join(", ")}${droppedNote(m)}`] : [])]),
			"\tdb -1 ; end",
			"",
		);
	},
	// One db row per Pokémon (level, species, then any moves); the group ends at the next label.
	rows: (lines, start, t, width, errors) => {
		if (width !== "8-bit") {
			errors.push(`trainer parties written as one db row per Pokémon need 8-bit species, but this project's are ${width}`);
			return;
		}
		let next = start + 1, count = 0;
		for (; next < lines.length && !/^[A-Za-z_]\w*:/.test(lines[next]!); next++) if (/^\s*db\s+"/.test(lines[next]!)) count++;
		let end = next;
		while (end > start + 1 && !lines[end - 1]!.trim()) end--;
		lines.splice(end, 0,
			"",
			`\t; ${t.cseClass} (${count + 1})`,
			`\tdb "${t.name}@", ${trainerType(t)} ; ported from Gen 1's ${t.source}`,
			...t.mons.map((m) => `\tdb ${String(m.level).padStart(2)}, ${[m.species, ...(m.moves ?? [])].join(", ")}${droppedNote(m)}`),
			"\tdb -1 ; end",
		);
	},
	// def_trainer … end_trainer, the class's macros working out the party's type; the group ends at
	// the next SECTION. A Pokémon with no form given has its plain form.
	"def-trainer": (lines, start, t) => {
		let end = start + 1;
		while (end < lines.length && !/^\s*SECTION\b/.test(lines[end]!)) end++;
		while (end > start + 1 && !lines[end - 1]!.trim()) end--;
		lines.splice(end, 0,
			"",
			`\tdef_trainer ${t.constName}, "${t.name}" ; ported from Gen 1's ${t.source}`,
			...t.mons.flatMap((m) => {
				const moves = (m.moves ?? []).filter((mv) => mv !== "NO_MOVE");
				return moves.length
					? [`\ttr_mon ${m.level}, ${m.species}`, `\t\ttr_moves ${moves.join(", ")}${droppedNote(m)}`]
					: [`\ttr_mon ${m.level}, ${m.species}${droppedNote(m)}`];
			}),
			"\tend_trainer",
		);
	},
};

function addTrainerParty(f: TextFile, t: TrainerAdd, group: string | undefined, formats: Formats<"trainerParties" | "indexWidth">, errors: string[]): void {
	const lines = linesOf(f);
	const start = group ? lines.findIndex((l) => l.startsWith(`${group}:`)) : -1;
	if (start < 0) {
		errors.push(`data/trainers/parties.asm has no group for ${t.cseClass}`);
		return;
	}
	ADD_PARTY[formats.trainerParties](lines, start, t, formats.indexWidth, errors);
	setLines(f, lines);
}

/** Trainer class -> its party group label, from TrainerGroups (class 1 is the first entry; `dba` or `dw` each). */
function trainerGroups(files: ReturnType<typeof gameFiles>): Map<string, string> {
	const classes = macroCalls(files.text("constants/trainer_constants.asm"), "trainerclass").map((c) => c[0]!);
	const text = files.text("data/trainers/party_pointers.asm");
	const groups = lines(text).flatMap((l) => l.match(/^(?:dba|dw)\s+(\w+)$/)?.[1] ?? []);
	return new Map(classes.slice(1).map((c, i) => [c, groups[i]!]));
}

/** A file the port will write (`data`), or only list in its report (no `data`), relative to the project. */
interface PortWrite {
	path: string;
	data?: string | Uint8Array;
	/** What the report says about it; records the tool keeps for itself aren't listed. */
	action?: string;
}

/** A port worked out but not written yet: its report, what it would write, and what each file held when read. */
export interface PortPlan {
	report: PortReport;
	config: Config;
	tileset: string;
	/** Empty when the port stops before writing (a dry run, unpaired blocks, errors, a confirm). */
	writes: PortWrite[];
	reads: Reads;
}

export type PortOptions = { dryRun: boolean; force?: boolean; mapping?: Mapping };

export function portMap(config: Config, gen1Const: string, options: PortOptions): PortReport {
	return commitPort(planPort(config, gen1Const, options));
}

/** Work out a port, reading the project but writing nothing. */
export function planPort(config: Config, gen1Const: string, options: PortOptions): PortPlan {
	const { value, reads } = noteReads(() => planWrites(config, gen1Const, options));
	return { ...value, config, reads };
}

/**
 * Write a planned port, unless a file it writes changed since the plan read it (another program
 * wrote it): then nothing is written, and the report names each such file.
 */
export function commitPort(plan: PortPlan): PortReport {
	const { report, writes } = plan;
	if (!writes.length) return report;
	const root = gameFiles(plan.config, "cse").root;
	const changed = writes.filter((w) => w.data !== undefined && changedSince(plan.reads, join(root, w.path)));
	if (changed.length) {
		for (const w of changed) report.errors.push(`${w.path} was changed by another program after the port read it; nothing was written, so port again`);
		return report;
	}
	for (const w of writes) {
		if (w.data !== undefined) {
			mkdirSync(dirname(join(root, w.path)), { recursive: true });
			writeFileSync(join(root, w.path), w.data);
		}
		if (w.action) report.files.push({ path: w.path, action: w.action });
	}
	report.written = true;
	report.unusedAdded = unusedAddedBlocks(plan.config, plan.tileset); // now that the .ablk is written
	return report;
}

/** How many of each kind of event a map has, by their marks. */
export function eventCounts(ev: MapEvents): { items: number; hiddenItems: number; signs: number; people: number; trainers: number } {
	const count = (kind: EventMark["kind"]) => ev.marks.filter((m) => m.kind === kind).length;
	return { items: count("item"), hiddenItems: count("hidden"), signs: count("sign"), people: count("person"), trainers: ev.trainers.length };
}

/** The features every port writes in; trainers and starting flags add theirs when a map has them. */
const PORT_FEATURES = ["tileColors", "tilesetSize", "blockFiles", "mapGroups", "mapHeader", "mapAttributes", "collisionNames", "eventFlags"] as const;

function planWrites(config: Config, gen1Const: string, options: PortOptions): Omit<PortPlan, "config" | "reads"> {
	const ctx = portContext(config, gen1Const, options.mapping);
	const { entry, gen1Map, cseTileset, result } = ctx;
	const cseFiles = gameFiles(config, "cse");
	const root = cseFiles.root;
	const report: PortReport = {
		map: gen1Const,
		cseMap: entry.const,
		dryRun: options.dryRun,
		written: false,
		unpaired: result.unpaired,
		appendedBlocks: 0,
		warpSquares: [],
		unusedAdded: [],
		reconciled: ctx.reconciled,
		conflicts: [...result.blocks.values()].filter((b) => b.conflicts.length).map((b) => ({ gen1Block: b.gen1, quadrants: b.conflicts })),
		walkIssues: [],
		pairEdges: [],
		warps: [],
		connections: [],
		files: [],
		errors: [],
		missing: [],
		events: { items: 0, hiddenItems: 0, signs: 0, people: 0, trainers: 0, notes: [] },
	};
	// Events (a replaced map keeps its own script, so it gets none)
	const gen1Files = gameFiles(config, entry.game);

	const events = portEvents(config, gen1Const, entry, gen1Map.name);
	const formats = formatsOf(cseFiles, PORT_FEATURES);
	// Trainers and starting flags need their formats only when the map has some.
	const extra: FeatureId[] = [...(events.trainers.length ? ["trainerParties", "indexWidth"] as const : []), ...(events.initFlags.length ? ["startingFlags"] as const : [])];
	let more: Partial<Formats<"trainerParties" | "indexWidth" | "startingFlags">> = {};
	try {
		more = formatsOf(cseFiles, extra) as typeof more;
	} catch (e) {
		report.errors.push(e instanceof Error ? e.message : String(e));
	}
	const flags = flagNeeds(cseFiles.text("constants/event_flags.asm"), events.flags);
	if (flags.needed > flags.room) {
		report.errors.push(`event flags: this map needs ${flags.needed} new ones, but only ${flags.room} are left (free places plus unused slots), so the cap must go up by at least ${flags.needed - flags.room}. The porter doesn't raise it. To make room, ${projectFeatures(cseFiles).moreFlags}`);
	}
	report.missing = events.missing;
	report.events = {
		...eventCounts(events),
		notes: entry.target === "replace" ? ["a replaced map keeps its own script; no events were written"] : events.report,
	};
	const final = finalGrid(gen1Map, ctx.gen1Coll, result, cseTileset, ctx.tilesetEntry.warpColl, ctx.collisionNames, events.collisionSquares);
	report.appendedBlocks = final.appended.length;
	report.warpSquares = final.warps;
	report.unusedAdded = unusedAddedBlocks(config, cseTileset.constName, final.grid);
	const cseResult = withAppended(cseTileset, final.appended);
	const diff = walkabilityDiff(gen1Map, ctx.gen1Coll, final.grid, cseResult);
	report.walkIssues = diff.issues;
	report.pairEdges = diff.edges;
	if (cseResult.blockCount > 256) report.errors.push(`${cseTileset.constName} would have ${cseResult.blockCount} blocks; the limit is 256`);
	if (gen1Map.borderBlock !== undefined && result.blocks.get(gen1Map.borderBlock)?.cse === undefined) {
		report.errors.push(`border block $${gen1Map.borderBlock.toString(16)} is unpaired`);
	}

	// Warps
	const cseMaps = mapConsts(cseFiles.text("constants/map_constants.asm"));
	const table = mapTable(root);
	const objects = `data/maps/objects/${gen1Map.name}.asm`;
	const gen1Warps = gen1Files.exists(objects) ? macroCalls(gen1Files.text(objects), "warp_event") : [];
	gen1Warps.forEach((w, i) => {
		const [x, y, dest, warp] = [Number(w[0]), Number(w[1]), w[2] ?? "", Number(w[3])];
		const pw: PortWarp = { gen1: { x, y, dest, warp } };
		const override = entry.warps[String(i + 1)];
		if (override) pw.cse = override;
		else if (dest === "LAST_MAP") {
			if (entry.lastMap) pw.cse = entry.lastMap;
			else pw.reason = "lastMap isn't set in tables/maps.json";
		} else if (table[dest]) {
			const target = table[dest]!;
			if (cseMaps.has(target.const) || target.const === entry.const) pw.cse = { map: target.const, warp };
			else pw.reason = `${target.const} isn't ported yet`;
		} else if (cseMaps.has(dest)) {
			pw.reason = `${dest} exists in the project with its own warp order; add a warps entry in tables/maps.json`;
		} else {
			pw.reason = `${dest} isn't in the project`;
		}
		report.warps.push(pw);
	});

	// Connections
	const headerPath = `data/maps/headers/${gen1Map.name}.asm`;
	const connectionLines: string[] = [], dirs: string[] = [];
	const attrRows = macroCalls(cseFiles.text("data/maps/attributes.asm"), "map_attributes");
	for (const c of gen1Files.exists(headerPath) ? macroCalls(gen1Files.text(headerPath), "connection") : []) {
		const [dir, , target, offset] = c;
		const t = table[target ?? ""];
		const cseConst = t?.const ?? target ?? "";
		const row = attrRows.find((r) => r[1] === cseConst);
		if (row) {
			connectionLines.push(`\tconnection ${dir}, ${row[0]}, ${cseConst}, ${offset}`);
			dirs.push(dir!);
			report.connections.push({ dir: dir!, target: cseConst, included: true });
		} else {
			report.connections.push({ dir: dir!, target: cseConst, included: false, reason: "not in the project" });
		}
	}

	// A map edited outside the tool since the last port (Polished Map++): its size, then its blocks.
	const gen1Size = { width: gen1Map.width, height: gen1Map.height };
	const cseSize = cseMaps.get(entry.const);
	if (cseSize && (cseSize.width !== gen1Size.width || cseSize.height !== gen1Size.height)) {
		report.errors.push(`${entry.const} is ${cseSize.width}x${cseSize.height} in constants/map_constants.asm but ${gen1Size.width}x${gen1Size.height} in Gen 1; it was resized outside the tool, and porting would write a ${gen1Size.width}x${gen1Size.height} .ablk against it`);
	}
	const blockBytes = Uint8Array.from(final.grid.map((b) => b ?? 0));
	const blockFile = BLOCK_FILES[formats.blockFiles];
	const ablkPath = blockFile.path(entry.name);
	if (cseFiles.exists(ablkPath)) {
		const onDisk = cseFiles.bytes(ablkPath);
		const record = readPortRecord(root, entry.const);
		const same = onDisk.length === blockBytes.length && onDisk.every((v, i) => v === blockBytes[i]);
		if (!same && (!record || record.ablk !== sha1(onDisk))) {
			const differ: { x: number; y: number }[] = [];
			for (let i = 0; i < blockBytes.length; i++) {
				if (onDisk[i] !== blockBytes[i]) differ.push({ x: i % gen1Map.width, y: Math.floor(i / gen1Map.width) });
			}
			report.outsideEdits = { path: ablkPath, reason: record ? "changed" : "no-record", blocks: differ };
		}
	}
	report.needsConfirm = !!report.outsideEdits && !options.force;

	const tileset = cseTileset.constName;
	if (report.unpaired.length || report.missing.length || report.errors.length || options.dryRun || report.needsConfirm) return { report, tileset, writes: [] };

	// What to write (commitPort writes it)
	const writes: PortWrite[] = [];
	const write = (path: string, data: string | Uint8Array, action?: string) => {
		noteUnread(join(root, path));
		writes.push({ path, data, action });
	};
	const inProject = (abs: string) => relative(root, abs).split(sep).join("/");
	const appended = final.appended;
	if (appended.length) {
		const ts = cseTileset.files;
		const meta = cseFiles.bytes(ts.blocks!);
		write(ts.blocks!, Buffer.concat([meta, Buffer.from(appended.flatMap((b) => b.meta))]), `+${appended.length} blocks`);
		// A palette-map tileset has no attributes file: its blocks take their tiles' colors.
		if (ts.attrs) write(ts.attrs, Buffer.concat([cseFiles.bytes(ts.attrs), Buffer.from(appended.flatMap((b) => b.attr))]), `+${appended.length} blocks`);
		const coll = openText(root, ts.collision!);
		const lines = linesOf(coll);
		// A line already there for a new block's number (past the tileset's last block, so nothing
		// read it) is replaced; the rest go after the last line.
		const tilecolls = lines.flatMap((l, i) => (/^\s*tilecoll\b/.test(l) ? [i] : []));
		const rest: string[] = [];
		appended.forEach((b, k) => {
			const line = `\ttilecoll ${b.coll.join(", ")} ; ${(cseTileset.blockCount + k).toString(16).padStart(2, "0")}`;
			const at = tilecolls[cseTileset.blockCount + k];
			if (at === undefined) rest.push(line);
			else lines[at] = line;
		});
		let last = lines.length;
		while (last > 0 && lines[last - 1]!.trim() === "") last--;
		lines.splice(last, 0, ...rest);
		setLines(coll, lines);
		write(coll.path, coll.text, `+${appended.length} tilecoll lines`);
		write(inProject(addedBlocksPath(root, tileset)), addedBlocksRecord(root, tileset, appended.map((_, k) => cseTileset.blockCount + k)));
	}
	write(ablkPath, blockBytes, "written");
	write(inProject(portRecordPath(root, entry.const)), portRecordText({ ablk: sha1(blockBytes), gen1: gen1Const, at: new Date().toISOString() }));

	const edits: [string, (f: TextFile) => void][] = [
		["constants/map_constants.asm", (f) => addMapConst(f, entry, gen1Map.width, gen1Map.height, GROUP_STYLES[formats.mapGroups], report.errors)],
		["data/maps/maps.asm", (f) => addMapHeader(f, entry, cseTileset.constName, formats.mapHeader, GROUP_STYLES[formats.mapGroups], report.errors)],
		["data/maps/attributes.asm", (f) => setMapAttributes(f, entry, result.blocks.get(gen1Map.borderBlock ?? 0)?.cse ?? 0, connectionLines, dirs, formats.mapAttributes)],
		["data/maps/blocks.asm", (f) => addBeforeLastEndsection(f, new RegExp(`^${blockFile.label(entry.name)}:`), [`${blockFile.label(entry.name)}:`, `\tINCBIN "${blockFile.incbin(entry.name)}"`], report.errors)],
		["data/maps/scripts.asm", (f) => addBeforeLastEndsection(f, new RegExp(`^INCLUDE "maps/${entry.name}\\.asm"`), [`INCLUDE "maps/${entry.name}.asm"`], report.errors)],
		["constants/event_flags.asm", (f) => EVENT_FLAGS[formats.eventFlags](f, events.flags, report.errors)],
	];
	if (more.startingFlags) {
		const starting = STARTING_FLAGS[more.startingFlags];
		edits.push([starting.file, (f) => starting.add(f, events.initFlags, report.errors)]);
	}
	// Trainers: a constant at the end of its class, then its party at the end of the class's group
	// (rerunning reuses a trainer whose constant is already there).
	if (events.trainers.length && more.trainerParties && more.indexWidth) {
		const partyFormats = { trainerParties: more.trainerParties, indexWidth: more.indexWidth };
		const consts = openText(root, "constants/trainer_constants.asm");
		const parties = openText(root, "data/trainers/parties.asm");
		const groups = trainerGroups(cseFiles);
		for (const t of events.trainers) {
			// def_trainer checks each party's constant against its number.
			const count = partyFormats.trainerParties === "def-trainer" ? defTrainerCount(parties, groups.get(t.cseClass)) : undefined;
			if (addTrainerConst(consts, t, report.errors, count === undefined ? undefined : count + 1)) addTrainerParty(parties, t, groups.get(t.cseClass), partyFormats, report.errors);
		}
		if (consts.changed) write(consts.path, consts.text, "updated (trainers)");
		if (parties.changed) write(parties.path, parties.text, "updated (trainer parties)");
	}
	for (const [path, edit] of edits) {
		const f = openText(root, path);
		edit(f);
		if (f.changed) write(path, f.text, "updated");
	}
	const scriptPath = `maps/${entry.name}.asm`;
	if (entry.target === "replace" && cseFiles.exists(scriptPath) && !cseFiles.text(scriptPath).startsWith(GENERATED)) {
		writes.push({ path: scriptPath, action: "kept (the replaced map's own script)" });
	} else if (cseFiles.exists(scriptPath) && !cseFiles.text(scriptPath).startsWith(GENERATED)) {
		report.errors.push(`${scriptPath} exists without the generated header; left as it is`);
	} else {
		write(scriptPath, SCRIPT_FILES[formats.mapAttributes](entry, gen1Const, report.warps, events), "written");
	}
	return { report, tileset, writes };
}
