/** Records live in the project (<project>/tools/gen1-map-porter/ports/<CSE_CONST>.json), committed with it. */
function portRecordPath(projectRoot: string, cseConst: string): string {
	return join(projectToolDir(projectRoot), "ports", `${cseConst}.json`);
}

/** Which blocks this tool appended to a tileset in a project (ports/tilesets/<T>.json). */
function addedBlocksPath(projectRoot: string, tilesetConst: string): string {
	return join(dirname(portRecordPath(projectRoot, "x")), "tilesets", `${tilesetConst}.json`);
}

export function readAddedBlocks(projectRoot: string, tilesetConst: string): number[] {
	const path = addedBlocksPath(projectRoot, tilesetConst);
	return fileExists(path) ? ((JSON.parse(readBytes(path).toString("utf8")) as { added: number[] }).added ?? []) : [];
}

/** The added-blocks record with `ids` added. */
function addedBlocksRecord(projectRoot: string, tilesetConst: string, ids: number[]): string {
	const added = [...new Set([...readAddedBlocks(projectRoot, tilesetConst), ...ids])].sort((a, b) => a - b);
	return JSON.stringify({ tileset: tilesetConst, added }, null, "\t") + "\n";
}

/**
 * Blocks this tool appended to the tileset that no map on it uses (D38). `pending` is a map about
 * to be written, whose blocks count as used.
 */
export function unusedAddedBlocks(config: Config, tilesetConst: string, pending: (number | undefined)[] = []): number[] {
	const files = gameFiles(config, "cse");
	const added = readAddedBlocks(files.root, tilesetConst);
	if (!added.length) return [];
	const used = cseTilesetUsage(files, tilesetConst, formatsOf(files, ["mapHeader", "blockFiles"]));
	for (const b of pending) if (b !== undefined) used.add(b);
	return added.filter((b) => !used.has(b));
}

/** Whether the tool has written this CSE map in this project. */
export function isPorted(projectRoot: string, cseConst: string): boolean {
	return existsSync(portRecordPath(projectRoot, cseConst));
}

