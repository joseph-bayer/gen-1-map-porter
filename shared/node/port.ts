interface TextFile {
	path: string;
	text: string;
	eol: string;
	changed: boolean;
}

function openText(root: string, path: string): TextFile {
	const text = readBytes(join(root, path)).toString("utf8");
	return { path, text, eol: text.includes("\r\n") ? "\r\n" : "\n", changed: false };
}

function linesOf(f: TextFile): string[] {
	return f.text.split(/\r?\n/);
}

function setLines(f: TextFile, lines: string[]): void {
	const text = lines.join(f.eol);
	if (text !== f.text) {
		f.text = text;
		f.changed = true;
	}
}

/** Insert `insert` (lines) before the first line matching `before`, after line index `from`. */
function insertBefore(f: TextFile, before: RegExp, insert: string[], from = 0): boolean {
	const lines = linesOf(f);
	for (let i = from; i < lines.length; i++) {
		if (before.test(lines[i]!)) {
			lines.splice(i, 0, ...insert);
			setLines(f, lines);
			return true;
		}
	}
	return false;
}

function lastIndex(lines: string[], re: RegExp): number {
	for (let i = lines.length - 1; i >= 0; i--) if (re.test(lines[i]!)) return i;
	return -1;
}

