/**
 * How a project's map groups are found, per way of grouping maps: in constants/map_constants.asm,
 * a group's map_const block (where its lines are counted from and to, and where a new line goes);
 * and in data/maps/maps.asm, the section its header rows are in.
 */
interface GroupStyle {
	/** The group's map_const block: its newgroup line, the line it ends before, and where a new map_const goes. */
	block(lines: string[], group: string): { start: number; end: number; insertAt: number } | undefined;
	/** The group whose block holds map_constants.asm line `at`. */
	groupAt(lines: string[], at: number): string | undefined;
	/** What map_constants.asm lacks when a group isn't there. */
	missing(group: string): string;
	/** In maps.asm: the line a new header row for the group goes before, if the group has a section. */
	headerAt(lines: string[], group: string): number | undefined;
	/** In maps.asm: the group whose section holds line `at`. */
	headerSection(lines: string[], at: number): string | undefined;
	/** What maps.asm lacks when a group has no section. */
	headerMissing(group: string): string;
}

/** Every newgroup line's index. */
const newgroupLines = (lines: string[]) => lines.flatMap((l, i) => (/^\s*newgroup\b/.test(l) ? [i] : []));

export const GROUP_STYLES: Record<Supported<"mapGroups">, GroupStyle> = {
	// `newgroup NAME` … `endgroup`; header rows end with `assert_table_length NUM_<NAME>_MAPS`.
	named: {
		block(lines, group) {
			const start = lines.findIndex((l) => new RegExp(`^\\s*newgroup\\s+${group}\\b`).test(l));
			if (start < 0) return undefined;
			let end = start + 1;
			while (end < lines.length && !/^\s*endgroup\b/.test(lines[end]!)) end++;
			return { start, end, insertAt: end };
		},
		groupAt(lines, at) {
			for (let i = at; i >= 0; i--) {
				const m = lines[i]!.match(/^\s*newgroup\s+(\w+)/);
				if (m) return m[1];
			}
			return undefined;
		},
		missing: (group) => `newgroup ${group}`,
		headerAt(lines, group) {
			const at = lines.findIndex((l) => new RegExp(`^\\s*assert_table_length\\s+NUM_${group}_MAPS\\b`).test(l));
			return at < 0 ? undefined : at;
		},
		headerSection: (lines, at) => lines.slice(at).find((l) => /^\s*assert_table_length\s+NUM_\w+_MAPS\b/.test(l))?.match(/NUM_(\w+)_MAPS/)?.[1],
		headerMissing: (group) => `assert_table_length NUM_${group}_MAPS`,
	},
	// Groups are numbered by their order (the Nth `newgroup`); header rows follow `MapGroupN:`.
	unnamed: {
		block(lines, group) {
			if (!/^[1-9]\d*$/.test(group)) return undefined;
			const starts = newgroupLines(lines);
			const start = starts[Number(group) - 1];
			if (start === undefined) return undefined;
			let end = starts[Number(group)] ?? lines.length;
			const stop = lines.findIndex((l, i) => i > start && /^\s*DEF\s+NUM_MAP_GROUPS\b/.test(l));
			if (stop >= 0 && stop < end) end = stop;
			let last = start;
			for (let i = start + 1; i < end; i++) if (/^\s*map_const\s/.test(lines[i]!)) last = i;
			return { start, end, insertAt: last + 1 };
		},
		groupAt(lines, at) {
			const n = newgroupLines(lines).filter((i) => i <= at).length;
			return n ? String(n) : undefined;
		},
		missing: (group) => `group ${group} (a ${group}th newgroup)`,
		headerAt(lines, group) {
			const label = lines.findIndex((l) => new RegExp(`^MapGroup${group}:`).test(l));
			if (label < 0) return undefined;
			let last = label;
			for (let i = label + 1; i < lines.length && !/^\S+:/.test(lines[i]!); i++) if (/^\s*map\s/.test(lines[i]!)) last = i;
			return last + 1;
		},
		headerSection(lines, at) {
			for (let i = at; i >= 0; i--) {
				const m = lines[i]!.match(/^MapGroup(\d+):/);
				if (m) return m[1];
			}
			return undefined;
		},
		headerMissing: (group) => `MapGroup${group}:`,
	},
};

/** Rewrite the "; N" count comments of a group's map_const lines, 1 up. */
function renumberGroup(lines: string[], group: string, style: GroupStyle): void {
	const block = style.block(lines, group);
	if (!block) return;
	let n = 0;
	for (let i = block.start + 1; i < block.end; i++) {
		if (/^\s*map_const\s/.test(lines[i]!)) lines[i] = lines[i]!.replace(/;\s*\d+\s*$/, `; ${String(++n).padStart(2)}`);
	}
}

/**
 * The map's map_const line, in its group's block. A map whose group changed (Map settings) moves
 * from its old block to the end of the new one; both blocks' count comments are redone.
 */
function addMapConst(f: TextFile, entry: MapEntry, width: number, height: number, style: GroupStyle, errors: string[]): void {
	const lines = linesOf(f);
	const existing = lines.findIndex((l) => new RegExp(`^\\s*map_const\\s+${entry.const},`).test(l));
	const oldGroup = existing >= 0 ? style.groupAt(lines, existing) : undefined;
	if (existing >= 0 && oldGroup === entry.group) return;
	if (!style.block(lines, entry.group)) {
		errors.push(`constants/map_constants.asm has no ${style.missing(entry.group)}`);
		return;
	}
	if (existing >= 0) lines.splice(existing, 1); // moving groups: out of the old block first
	const block = style.block(lines, entry.group)!;
	let count = 0, sample: RegExpMatchArray | null = null;
	for (let i = block.start + 1; i < block.end; i++) {
		const m = lines[i]!.match(/^(\s*map_const\s+)(\S+,\s*\d+),/);
		if (m) {
			count++;
			sample = m;
		}
	}
	// Line the width up with the group's other lines: its two-digit column ends where theirs does.
	const prefix = sample?.[1] ?? "\tmap_const ";
	const field = Math.max((sample?.[2] ?? "").length - 2, entry.const.length + 2);
	const line = `${prefix}${`${entry.const},`.padEnd(field)}${String(width).padStart(2)}, ${String(height).padStart(2)} ; ${String(count + 1).padStart(2)}`;
	lines.splice(block.insertAt, 0, line);
	if (oldGroup) renumberGroup(lines, oldGroup, style); // the maps after it in its old group move up one
	setLines(f, lines);
}

/** A map's header row, per header layout. */
const HEADER_ROW: Record<Supported<"mapHeader">, (entry: MapEntry, tileset: string) => string> = {
	"fish-group": (e, tileset) => `\tmap ${e.name}, ${tileset}, ${e.environment}, ${e.landmark}, ${e.music}, ${e.noPhone}, ${e.palette}, ${e.fishGroup}`,
	sign: (e, tileset) => `\tmap ${e.name}, ${tileset}, ${e.environment}, ${e.sign}, ${e.landmark}, ${e.music}, ${e.noPhone}, ${e.palette}`,
};

/**
 * The map's header row. A map the tool made gets the whole row from its entry, so Map settings
 * changes reach it; a replaced CSE map keeps its row and only takes the new tileset.
 */
function addMapHeader(f: TextFile, entry: MapEntry, cseTileset: string, layout: Supported<"mapHeader">, style: GroupStyle, errors: string[]): void {
	const lines = linesOf(f);
	const row = HEADER_ROW[layout](entry, cseTileset);
	const at = lines.findIndex((l) => new RegExp(`^\\s*map\\s+${entry.name},`).test(l));
	// A map the tool made whose group changed: its row leaves the old group's section, then goes in below.
	const section = at >= 0 ? style.headerSection(lines, at) : undefined;
	if (style.headerAt(lines, entry.group) === undefined) {
		errors.push(`data/maps/maps.asm has no ${style.headerMissing(entry.group)}`);
		return;
	}
	if (at >= 0 && entry.target !== "replace" && section !== entry.group) {
		lines.splice(at, 1);
	} else if (at >= 0) {
		lines[at] = entry.target === "replace"
			? lines[at]!.replace(new RegExp(`^(\\s*map\\s+${entry.name}(?:,\\s*[^,\\s]+){${HEADER_COLUMNS[layout].tileset - 1}},\\s*)[^,\\s]+`), (_, head: string) => head + cseTileset)
			: row + (lines[at]!.match(/\s*;.*$/)?.[0] ?? "");
		setLines(f, lines);
		return;
	}
	lines.splice(style.headerAt(lines, entry.group)!, 0, row);
	setLines(f, lines);
}

/** A border block as a map_attributes row writes it, per layout: CSE pads it to two digits, Polished Crystal doesn't. */
const BORDER: Record<Supported<"mapAttributes">, (border: number) => string> = {
	"connection-mask": (b) => `$${b.toString(16).padStart(2, "0")}`,
	"connection-lines": (b) => `$${b.toString(16).padStart(2, "0")}`,
	"script-header": (b) => `$${b.toString(16)}`,
};

/** The connection lines in the order north, south, west, east, which the connection macro needs. */
function connectionsInOrder(connections: string[], dirs: string[]): string[] {
	const order = ["north", "south", "west", "east"];
	return connections.map((line, i) => ({ line, at: order.indexOf(dirs[i]!) })).sort((a, b) => a.at - b.at).map((c) => c.line);
}

/** A map's map_attributes line and its connection lines, per layout. */
const ATTRIBUTES_ROWS: Record<Supported<"mapAttributes">, (entry: MapEntry, border: number, connections: string[], dirs: string[]) => string[]> = {
	"connection-mask": (entry, border, connections, dirs) => {
		const mask = dirs.length ? dirs.map((d) => d.toUpperCase()).join(" | ") : "0";
		return [`\tmap_attributes ${entry.name}, ${entry.const}, ${BORDER["connection-mask"](border)}, ${mask}`, ...connections];
	},
	// The connection lines set the mask themselves, and must come north, south, west, east.
	"connection-lines": (entry, border, connections, dirs) => [`\tmap_attributes ${entry.name}, ${entry.const}, ${BORDER["connection-lines"](border)}`, ...connectionsInOrder(connections, dirs)],
	"script-header": (entry, border, connections, dirs) => [`\tmap_attributes ${entry.name}, ${entry.const}, ${BORDER["script-header"](border)}`, ...connectionsInOrder(connections, dirs)],
};

function setMapAttributes(f: TextFile, entry: MapEntry, border: number, connections: string[], dirs: string[], layout: Supported<"mapAttributes">): void {
	const lines = linesOf(f);
	const block = ATTRIBUTES_ROWS[layout](entry, border, connections, dirs);
	const at = lines.findIndex((l) => new RegExp(`^\\s*map_attributes\\s+${entry.name},`).test(l));
	if (at >= 0 && entry.target === "replace") {
		// A replaced CSE map keeps its connections (its neighbors are CSE's); only the border changes.
		const hex = BORDER[layout](border);
		lines[at] = lines[at]!.replace(new RegExp(`^(\\s*map_attributes\\s+${entry.name},\\s*\\w+,\\s*)[^,\\s]+`), (_, head: string) => head + hex);
		setLines(f, lines);
	} else if (at >= 0) {
		let end = at + 1;
		while (end < lines.length && /^\s*connection\s/.test(lines[end]!)) end++;
		lines.splice(at, end - at, ...block);
	} else {
		let last = lines.length;
		while (last > 0 && lines[last - 1]!.trim() === "") last--;
		lines.splice(last, 0, ...block);
	}
	setLines(f, lines);
}

